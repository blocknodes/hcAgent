def main():
    sets = load_sets()
    fail_qs = [x['query'] for x in FAILS if not x['tool_ok']]
    other = [(dom, r['期望工具'], r['query'].strip())
             for dom in sets if dom != 'device' for r in sets[dom]]
    dev_ok = [r['query'].strip() for r in sets['device'] if r['query'].strip() not in fail_qs]

    pipeline = [(lab, re.compile(pat)) for lab, pat in CANDIDATES]
    cov = []
    leak = []
    devok = []
    for q in fail_qs:
        for lab, rx in pipeline:
            if rx.search(q):
                cov.append((lab, q))
                break
    for dom, et, q in other:
        for lab, rx in pipeline:
            if rx.search(q):
                leak.append((dom, et, q, lab))
                break
    for q in dev_ok:
        for lab, rx in pipeline:
            if rx.search(q):
                devok.append((lab, q))
                break
    print(f"fail={len(fail_qs)}  other={len(other)}  dev_ok={len(dev_ok)}")
    print(f"\npipeline coverage: {len(set(x[1] for x in cov))}/{len(fail_qs)}")
    from collections import Counter
    lc = Counter(x[0] for x in cov)
    for lab, n in lc.most_common():
        print(f"   {lab}: {n}")
    print(f"\nLEAK other-domains: {len(leak)}")
    for x in leak[:30]:
        print(f"   {x}")
    print(f"\nHIT-in-dev-ok: {len(devok)}")
    le = Counter(x[0] for x in devok)
    for lab, n in le.most_common():
        print(f"   devok {lab}: {n}")


if __name__ == '__main__':
    main()